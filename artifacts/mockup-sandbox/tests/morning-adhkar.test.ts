import assert from "node:assert/strict";
import fs from "node:fs";
import { morningPlaylist, morningItemAt, morningWindowActive, parseMorningAdhkar, morningStartsAt } from "../src/components/mockups/prayer-themes/morning-adhkar.ts";
import { hadithDurationSeconds } from "../src/components/mockups/prayer-themes/hadith-timing.ts";
import { englishDigits } from "../src/components/mockups/prayer-themes/english-digits.ts";
import { hijriDisplay } from "../src/components/mockups/prayer-themes/browser-prayer-preferences.ts";
import { recitationParts } from "../src/components/mockups/prayer-themes/recitation-colors.ts";
const source = fs.readFileSync("../../mobile/prayer_times/assets/data/morning-adhkar.txt", "utf8");
const entries = parseMorningAdhkar(source);
const pool = Array.from({ length: 100 }, (_, i) => ({ text: `قال رسول الله: «حديث ${i}»`, number: i }));
const items = morningPlaylist(source, pool, 20261016);
assert.equal(entries.length, 30);
assert.equal(items.length, 48);
assert.deepEqual(items.filter(item => item.recitation).map(item => item.entry), entries);
assert.equal(new Set(items.filter(item => !item.recitation).map(item => item.entry.number)).size, 18);
assert.deepEqual(morningPlaylist(source, pool, 20261016), items);
assert.notDeepEqual(morningPlaylist(source, pool, 20261017), items);
const start = Date.UTC(2026, 9, 16, 2, 30);
const end = start + 90 * 60000;
assert.equal(morningStartsAt(start, 20, 10, 8), start + 38 * 60000);
assert.equal(morningStartsAt(start, 15, 12, 4), start + 31 * 60000);
assert.equal(morningStartsAt(start, 20, 0, 8), start + 20 * 60000 + 45000);
assert.equal(morningStartsAt(null, 20, 10, 8), null);
assert.equal(morningStartsAt(start, undefined, 10, 8), null);
assert.equal(morningWindowActive(start - 1, start, end), false);
assert.equal(morningWindowActive(start, start, end), true);
assert.equal(morningWindowActive(end, start, end), false);
assert.equal(morningWindowActive(start, null, end), false);
let elapsed = 0;
items.forEach((item, index) => {
  assert.equal(item.recitation, index % 8 < 5);
  assert.equal(morningItemAt(items, start + elapsed, start, end), null);
  assert.equal(morningItemAt(items, start + elapsed + 4999, start, end), null);
  assert.deepEqual(morningItemAt(items, start + elapsed + 5000, start, end), item);
  elapsed += (5 + hadithDurationSeconds(item.entry)) * 1000;
});
assert.equal(morningItemAt(items, start + elapsed, start, end), null);
assert.deepEqual(morningItemAt(items, start + elapsed + 5000, start, end), items[0]);
assert.equal(morningItemAt(items, end, start, end), null);
assert.equal(englishDigits("١٢٣٤٥٦٧٨٩٠ ۱۲۳۴۵۶۷۸۹۰ 123"), "1234567890 1234567890 123");
const hijri = hijriDisplay(new Date(start), { regionId: null, iqamaMinutes: {} });
assert.ok(!/[٠-٩۰-۹]/.test(hijri) && /\d/.test(hijri));
for (const item of entries) {
  const parts = recitationParts(item.text, true);
  assert.equal(parts.map(part => part.text).join(""), item.text);
  assert.ok(parts[0].recitation);
}
assert.equal(recitationParts(entries[28].text, true).at(-1)!.recitation, false);
console.log("Morning: 30 ordered adhkar, 5+3 groups, 5-second pauses, repeat/end boundaries, reward colors and English digits passed.");
