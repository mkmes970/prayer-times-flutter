def column(text):
    """Compact transcription: hour persists until the next explicit H:MM."""
    hour = None
    result = []
    for token in text.split():
        if ":" in token:
            h, m = token.split(":")
            hour, minute = int(h), int(m)
        else:
            minute = int(token)
        assert hour is not None and 1 <= hour <= 12 and 0 <= minute < 60
        result.append(f"{hour}:{minute:02d}")
    return result


