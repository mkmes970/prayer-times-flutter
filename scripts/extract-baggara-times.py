names = ["كانون الثاني", "شباط", "آذار", "نيسان", "أيار", "حزيران",
         "تموز", "آب", "أيلول", "تشرين الأول", "تشرين الثاني", "كانون الأول"]
keys = ["fajr", "sunrise", "dhuhr", "asr", "maghrib", "isha"]
lengths = [31, 29, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]
months = []
for month in range(1, 13):
    columns = [column(text) for text in raw[month]]
    assert all(len(c) == lengths[month - 1] for c in columns), (
        month, [len(c) for c in columns])
    days = [
        {"day": day + 1, **{key: columns[i][day] for i, key in enumerate(keys)}}
        for day in range(lengths[month - 1])
    ]
    # Validate daily sequence, explicitly interpreting the source's PM columns.
    for day in days:
        minutes = []
        for key in keys:
            h, m = map(int, day[key].split(":"))
            if key == "dhuhr":
                hour24 = h
            elif key in ("asr", "maghrib", "isha"):
                hour24 = h % 12 + 12
            else:
                hour24 = h % 12
            minutes.append(hour24 * 60 + m)
        assert minutes == sorted(minutes) and len(set(minutes)) == 6, (month, day)
    months.append({"month": month, "name": names[month - 1], "days": days})

